"""الإنذارات القانونية — Cease & Desist + إنذار مسبق للضحية

كلاهما وثيقة نصية تُشارك عبر قناة الضحية (تطبيق/بريد) —
النظام يُعد ولا يُرسل تلقائياً للمبتز (قرار قانوني موثق).
"""
from app.models.report import Report


def _articles(report: Report) -> list[str]:
    return [
        "ابتزاز إلكتروني بالتهديد بالنشر (حسب التشريع النافذ)",
        "انتهاك الخصوصية ونشر محتوى خاص دون رضا",
        "الابتزاز المالي عبر التهديد",
    ]


def cease_and_desist(report: Report) -> str:
    """خطاب إنذار رسمي للمبتز — يُرسل بقرار الضحية أو النيابة"""
    articles = "\n".join(f"  - {a}" for a in _articles(report))
    return "\n".join(
        [
            "إنذار وإشعار قانوني (CEASE & DESIST)",
            "=" * 56,
            f"المرجع: بلاغ {report.report_number} — موثق بسلسلة حفظ رقمية",
            "إلى: صاحب الحساب/الرقم التالي",
            f"  {report.sender_display} ({report.sender_raw})",
            "",
            "نحيطكم علماً بأن جميع مراسلاتكم موثقة ومحفوظة مشفرة",
            "ومسجلة لدى المنصة الوطنية لمكافحة الابتزاز الإلكتروني،",
            "وأن استمرار أي من الأفعال التالية:",
            "  - التهديد بالنشر أو التوزيع",
            "  - طلب مبالغ مالية أو مقابل أي نوع",
            "  - التحرش أو الاتصال المتكرر",
            "",
            "يُعد تكراراً للجريمة وترديداً للعقوبة، إضافة إلى:",
            articles,
            "",
            "المطالبة:",
            "  1. التوقف الفوري عن أي تواصل",
            "  2. عدم نشر أو توزيع أي محتوى",
            "  3. حذف أي محتوى محفوظ لديكم",
            "",
            "تنبيه: أي نشر للمحتوى يُوثق تلقائياً ويُضاف كتهمة مستقلة،",
            "والبصمات الرقمية للأدلة تثبت مصدرها وزمانها أمام الجهات المختصة.",
        ]
    )


def preemptive_notice(report: Report) -> str:
    """إشعار مسبق قصير — يجهزه النظام لترسله الضحية بنفسها إن أرادت"""
    return "\n".join(
        [
            "⚠️ إشعار مسبق",
            "تم توثيق هذه المحادثة وحفظ أدلتها مشفرة لدى المنصة الوطنية",
            "لمكافحة الابتزاز الإلكتروني (NAP-EX) — بلاغ رقم "
            f"{report.report_number}.",
            "أي نشر أو تهديد سيُضاف كتهمة مستقلة، والعقوبة تصل",
            "لسنوات سجن وغرامات مالية.",
            "أوصيكم بالتوقف والاستسلام للجهات المختصة.",
        ]
    )
